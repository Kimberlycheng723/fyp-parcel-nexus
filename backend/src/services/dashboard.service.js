function getPeriodConfig(period, { startDate } = {}) {
  const now = new Date();
  const selectedStart = startDate ? parseDateInput(startDate) : null;

  if (startDate && !selectedStart) {
    return { error: "INVALID_START_DATE" };
  }

  if (selectedStart) {
    if (period === "week") {
      return {
        period,
        label: "Selected 7 days",
        start: selectedStart,
        end: addDays(selectedStart, 7),
        previousStart: addDays(selectedStart, -7),
        previousEnd: selectedStart,
        comparisonLabel: "vs previous 7 days",
        trendStep: "1 day",
        trendFormat: "Dy, DD Mon"
      };
    }

    if (period === "month") {
      const end = addCalendarMonths(selectedStart, 1);
      return {
        period,
        label: "Selected month range",
        start: selectedStart,
        end,
        previousStart: addCalendarMonths(selectedStart, -1),
        previousEnd: selectedStart,
        comparisonLabel: "vs previous month",
        trendStep: "1 day",
        trendFormat: "DD Mon"
      };
    }

    return {
      period: "day",
      label: "Selected day",
      start: selectedStart,
      end: addDays(selectedStart, 1),
      previousStart: addDays(selectedStart, -1),
      previousEnd: selectedStart,
      comparisonLabel: "vs previous day",
      trendStep: "1 hour",
      trendFormat: "HH24:00"
    };
  }

  if (period === "week") {
    const start = addDays(now, -6);
    start.setHours(0, 0, 0, 0);
    const previousStart = addDays(start, -7);
    const previousEnd = start;

    return {
      period,
      label: "Last 7 days",
      start,
      end: now,
      previousStart,
      previousEnd,
      comparisonLabel: "vs previous 7 days",
      trendStep: "1 day",
      trendFormat: "Dy, DD Mon"
    };
  }

  if (period === "month") {
    const start = startOfMonth(now);
    const previousStart = addMonths(start, -1);
    const previousEnd = start;

    return {
      period,
      label: "This month",
      start,
      end: now,
      previousStart,
      previousEnd,
      comparisonLabel: "vs previous month",
      trendStep: "1 day",
      trendFormat: "DD Mon"
    };
  }

  const start = startOfDay(now);
  const previousStart = addDays(start, -1);

  return {
    period: "day",
    label: "Today",
    start,
    end: now,
    previousStart,
    previousEnd: start,
    comparisonLabel: "vs yesterday",
    trendStep: "1 hour",
    trendFormat: "HH24:00"
  };
}

function getGuardPeriodConfig(period = "today", { startDate } = {}) {
  const normalizedPeriod = period === "day" ? "today" : period;

  if (!VALID_GUARD_PERIODS.includes(period)) {
    return { error: "INVALID_GUARD_PERIOD" };
  }

  const selectedStart = startDate ? parseDateInput(startDate) : startOfDay(new Date());

  if (startDate && !selectedStart) {
    return { error: "INVALID_START_DATE" };
  }

  if (normalizedPeriod === "week") {
    return {
      period: "week",
      selected: "week",
      label: "Selected 7 days",
      start: selectedStart,
      end: addDays(selectedStart, 7)
    };
  }

  if (normalizedPeriod === "month") {
    return {
      period: "month",
      selected: "month",
      label: "Selected month range",
      start: selectedStart,
      end: addCalendarMonths(selectedStart, 1)
    };
  }

  return {
    period: "day",
    selected: "today",
    label: "Selected day",
    start: selectedStart,
    end: addDays(selectedStart, 1)
  };
}

