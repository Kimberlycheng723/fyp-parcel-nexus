function addPdfHeader(doc, metadata) {
  doc.fontSize(18).fillColor("#0b2239").text(metadata.reportTitle);
  doc.moveDown(0.2);
  doc.fontSize(11).fillColor("#4f5b67").text("GEM Condominium");
  doc.moveDown(0.8);
  doc.fontSize(9).fillColor("#4f5b67");
  doc.text(`Generated at: ${metadata.generatedAt}`);
  doc.text(`Generated by: ${metadata.generatedBy}${metadata.generatedByEmail ? ` (${metadata.generatedByEmail})` : ""}`);
  doc.text(`Period: ${metadata.period}`);
  doc.text(`Range: ${metadata.rangeStart} to ${metadata.rangeEnd}`);
  doc.moveDown(1);
}

function ensurePdfSpace(doc, height = 90) {
  if (doc.y + height > doc.page.height - doc.page.margins.bottom) {
    doc.addPage();
  }
}

function addPdfSectionTitle(doc, title) {
  ensurePdfSpace(doc, 45);
  doc.moveDown(0.5);
  doc.fontSize(13).fillColor("#0b2239").text(title);
  doc.moveDown(0.25);
}

function addPdfRows(doc, headers, rows) {
  const line = (values, isHeader = false) => {
    ensurePdfSpace(doc, 28);
    doc
      .fontSize(isHeader ? 8 : 8)
      .fillColor(isHeader ? "#0b2239" : "#2c3742")
      .font(isHeader ? "Helvetica-Bold" : "Helvetica")
      .text(values.map((value) => String(value ?? "")).join("   |   "), {
        width: doc.page.width - doc.page.margins.left - doc.page.margins.right
      });
    doc.moveDown(0.35);
  };

  line(headers, true);
  rows.forEach((row) => line(row));
  doc.font("Helvetica");
}

function addPdfBars(doc, rows, labelKey, valueKey) {
  const maxValue = Math.max(1, ...rows.map((row) => numberValue(row[valueKey])));

  rows.forEach((row) => {
    ensurePdfSpace(doc, 28);
    const value = numberValue(row[valueKey]);
    const barWidth = Math.round((value / maxValue) * 180);
    const y = doc.y + 3;
    doc.fontSize(8).fillColor("#2c3742").text(`${row[labelKey]} (${value})`, doc.x, doc.y, { width: 170 });
    doc.rect(doc.x + 180, y, 180, 8).fill("#edf0f2");
    doc.rect(doc.x + 180, y, barWidth, 8).fill("#0b2239");
    doc.moveDown(0.7);
  });
}

function buildPdfBuffer(render) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 42, size: "A4", bufferPages: true });
    const chunks = [];

    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    render(doc);
    const pageCount = doc.bufferedPageRange().count;

    for (let index = 0; index < pageCount; index += 1) {
      doc.switchToPage(index);
      doc
        .fontSize(8)
        .fillColor("#88919b")
        .text(`Parcel Nexus · Page ${index + 1} of ${pageCount}`, 42, doc.page.height - 34, {
          align: "center"
        });
    }

    doc.end();
  });
}

