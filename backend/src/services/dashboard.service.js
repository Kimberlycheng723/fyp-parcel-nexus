function buildReportFilename({ reportType, format, period, startDate }) {
  const datePart = startDate || new Date().toISOString().slice(0, 10);
  return `parcel-nexus-${reportSlug(reportType)}-${period}-${datePart}.${format}`;
}

async function buildReportContent({ reportType, format, config, metadata, requester }) {
  if (reportType === "dashboard_summary") {
    const dashboard = await getAdminDashboard({
      requester,
      period: config.period,
      startDate: metadata.requestedStartDate
    });

    if (dashboard.error) {
      return dashboard;
    }

    return {
      content: format === "csv"
        ? buildDashboardSummaryCsv({ metadata, dashboard })
        : await buildDashboardSummaryPdf({ metadata, dashboard })
    };
  }

  if (reportType === "parcel_records") {
    const records = await getParcelRecordsForReport(config);

    return {
      content: format === "csv"
        ? buildParcelRecordsCsv({ metadata, records })
        : await buildParcelRecordsPdf({ metadata, records })
    };
  }

  const summary = await getUserAccountSummaryForReport(config);

  return {
    content: format === "csv"
      ? buildUserAccountSummaryCsv({ metadata, summary })
      : await buildUserAccountSummaryPdf({ metadata, summary })
  };
}

export async function getAdminDashboard({ requester, period = "day", startDate }) {
  if (requester.role !== "ADMIN") {
    return { error: "FORBIDDEN" };
  }

  const normalizedPeriod = String(period || "day").trim().toLowerCase();

  if (!VALID_PERIODS.includes(normalizedPeriod)) {
    return { error: "INVALID_PERIOD" };
  }

  const config = getPeriodConfig(normalizedPeriod, { startDate });

  if (config.error) {
    return { error: config.error };
  }
  const [totalParcels, previousTotalParcels, collected, previousCollected, pendingData] = await Promise.all([
    getRangeParcelCount(config),
    getRangeParcelCount({
      start: config.previousStart,
      end: config.previousEnd
    }),
    getRangeCollectedCount(config),
    getRangeCollectedCount({
      start: config.previousStart,
      end: config.previousEnd
    }),
    getCurrentPendingAndOverdue()
  ]);
  const [disputeData, parcelTrend, statusDistribution, systemSummary, recentActivity] = await Promise.all([
    getDisputeKpi({
      start: config.start,
      end: config.end,
      previousStart: config.previousStart,
      previousEnd: config.previousEnd,
      comparisonLabel: config.comparisonLabel
    }),
    getParcelTrend(config),
    getStatusDistribution(),
    getSystemSummary(),
    getRecentActivity()
  ]);

  return {
    period: config.period,
    range: {
      label: config.label,
      start: toIso(config.start),
      end: toIso(config.end)
    },
    comparison_range: {
      start: toIso(config.previousStart),
      end: toIso(config.previousEnd)
    },
    kpis: {
      total_parcels: {
        label: "Parcels Logged",
        value: totalParcels,
        comparison_label: config.comparisonLabel,
        comparison_value: previousTotalParcels,
        change_percent: calculateChangePercent(totalParcels, previousTotalParcels)
      },
      pending_collection: {
        label: "Pending Collection",
        value: pendingData.pendingCollection,
        overdue_count: pendingData.overdueCount,
        comparison_label: config.comparisonLabel,
        comparison_value: null,
        change_percent: null,
        message: "Pending collection is a current operational count, not a historical snapshot."
      },
      collected: {
        label: "Collected Parcels",
        value: collected,
        comparison_label: config.comparisonLabel,
        comparison_value: previousCollected,
        change_percent: calculateChangePercent(collected, previousCollected)
      },
      open_disputes: disputeData.kpi
    },
    alert:
      pendingData.overdueCount > 0
        ? {
            type: "overdue",
            overdue_count: pendingData.overdueCount,
            message:
              pendingData.overdueCount === 1
                ? "1 parcel is overdue."
                : `${pendingData.overdueCount} parcels are overdue.`
          }
        : {
            type: "none",
            overdue_count: 0,
            message: ""
          },
    parcel_trend: parcelTrend,
    status_distribution: statusDistribution,
    dispute_summary: disputeData.summary,
    system_summary: systemSummary,
    recent_activity: recentActivity
  };
}

export async function getGuardDashboard({ requester, period = "today", startDate }) {
  if (requester.role !== "GUARD") {
    return { error: "GUARD_FORBIDDEN" };
  }

  const normalizedPeriod = String(period || "today").trim().toLowerCase();
  const config = getGuardPeriodConfig(normalizedPeriod, { startDate });

  if (config.error) {
    return { error: config.error };
  }

  const [summary, latestLoggedParcels, pendingCollectionParcels] = await Promise.all([
    getGuardSummary(config),
    getLatestLoggedParcelsForGuard(),
    getPendingCollectionParcelsForGuard()
  ]);
  const overdueCount = numberValue(summary.overdue_parcels);

  return {
    guard: {
      name: displayUserName(requester),
      email: requester.email
    },
    period: {
      selected: config.selected,
      start: toIso(config.start),
      end: toIso(config.end),
      label: config.label
    },
    summary,
    alert:
      overdueCount > 0
        ? {
            type: "overdue",
            count: overdueCount,
            message: overdueCount === 1 ? "1 parcel is overdue." : `${overdueCount} parcels are overdue.`
          }
        : {
            type: "none",
            count: 0,
            message: ""
          },
    latest_logged_parcels: latestLoggedParcels,
    pending_collection_parcels: pendingCollectionParcels,
    dispute_summary: {
      available: false,
      message: "Dispute module is not implemented yet."
    }
  };
}

export async function generateAdminReport({
  requester,
  reportType,
  format,
  period = "day",
  startDate
}) {
  if (requester.role !== "ADMIN") {
    return { error: "FORBIDDEN" };
  }

  const normalizedReportType = String(reportType || "").trim().toLowerCase();
  const normalizedFormat = String(format || "").trim().toLowerCase();
  const normalizedPeriod = String(period || "day").trim().toLowerCase();

  if (!VALID_REPORT_TYPES.includes(normalizedReportType)) {
    return { error: "INVALID_REPORT_TYPE" };
  }

  if (!VALID_REPORT_FORMATS.includes(normalizedFormat)) {
    return { error: "INVALID_FORMAT" };
  }

  if (!VALID_PERIODS.includes(normalizedPeriod)) {
    return { error: "INVALID_PERIOD" };
  }

  const config = getPeriodConfig(normalizedPeriod, { startDate });

  if (config.error) {
    return { error: config.error };
  }

  const metadata = createMetadata({
    reportType: normalizedReportType,
    format: normalizedFormat,
    config,
    requester,
    startDate
  });
  const reportContent = await buildReportContent({
    reportType: normalizedReportType,
    format: normalizedFormat,
    config,
    metadata,
    requester
  });

  if (reportContent.error) {
    return reportContent;
  }

  return {
    filename: buildReportFilename({
      reportType: normalizedReportType,
      format: normalizedFormat,
      period: normalizedPeriod,
      startDate
    }),
    contentType:
      normalizedFormat === "csv"
        ? "text/csv; charset=utf-8"
        : "application/pdf",
    content: reportContent.content
  };
}
