function toIso(value) {
  return value instanceof Date ? value.toISOString() : new Date(value).toISOString();
}

function startOfDay(date) {
  const result = new Date(date);
  result.setHours(0, 0, 0, 0);
  return result;
}

function startOfMonth(date) {
  return new Date(date.getFullYear(), date.getMonth(), 1);
}

function addDays(date, days) {
  const result = new Date(date);
  result.setDate(result.getDate() + days);
  return result;
}

function addMonths(date, months) {
  return new Date(date.getFullYear(), date.getMonth() + months, 1);
}

function addCalendarMonths(date, months) {
  const day = date.getDate();
  const result = new Date(date.getFullYear(), date.getMonth() + months, 1);
  const lastDay = new Date(result.getFullYear(), result.getMonth() + 1, 0).getDate();
  result.setDate(Math.min(day, lastDay));
  result.setHours(date.getHours(), date.getMinutes(), date.getSeconds(), date.getMilliseconds());
  return result;
}

function parseDateInput(value) {
  if (!value) {
    return null;
  }

  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {
    return null;
  }

  const [year, month, day] = value.split("-").map(Number);
  const date = new Date(year, month - 1, day);

  if (
    date.getFullYear() !== year ||
    date.getMonth() !== month - 1 ||
    date.getDate() !== day
  ) {
    return null;
  }

  date.setHours(0, 0, 0, 0);
  return date;
}

function calculateChangePercent(currentValue, comparisonValue) {
  if (comparisonValue === null || comparisonValue === undefined) {
    return null;
  }

  if (comparisonValue === 0) {
    return currentValue === 0 ? 0 : null;
  }

  return Number((((currentValue - comparisonValue) / comparisonValue) * 100).toFixed(2));
}

function numberValue(value) {
  return Number(value || 0);
}

function titleCaseReportType(value) {
  return String(value)
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function reportSlug(value) {
  return String(value || "")
    .replace(/_/g, "-")
    .replace(/[^a-z0-9-]/gi, "")
    .toLowerCase();
}

function displayUserName(user) {
  const name = `${user?.first_name || ""} ${user?.last_name || ""}`.trim();

  if (name) {
    return name;
  }

  return user?.email || "Admin";
}

function formatDateTime(value) {
  if (!value) {
    return "";
  }

  const date = value instanceof Date ? value : new Date(value);

  if (Number.isNaN(date.getTime())) {
    return "";
  }

  return date.toISOString();
}

function csvEscape(value) {
  if (value === null || value === undefined) {
    return "";
  }

  const text = String(value);

  if (/[",\n\r]/.test(text)) {
    return `"${text.replace(/"/g, '""')}"`;
  }

  return text;
}

function csvRow(values) {
  return values.map(csvEscape).join(",");
}

function csvSection(title, rows = []) {
  return [title, ...rows.map(csvRow), ""].join("\n");
}

