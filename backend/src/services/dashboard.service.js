async function getUserAccountSummaryForReport(config) {
  const [summaryResult, trendResult] = await Promise.all([
    pool.query(
      `
        SELECT role, status, COUNT(*)::int AS total_count
        FROM users
        WHERE role IN ('SUPER_ADMIN', 'ADMIN', 'GUARD', 'RESIDENT')
        GROUP BY role, status
        ORDER BY role, status
      `
    ),
    pool.query(
      `
        SELECT to_char(date_trunc('month', created_at), 'YYYY-MM') AS account_creation_month,
               COUNT(*)::int AS new_account_count
        FROM users
        WHERE role IN ('ADMIN', 'GUARD', 'RESIDENT')
          AND created_at >= $1
          AND created_at < $2
        GROUP BY date_trunc('month', created_at)
        ORDER BY date_trunc('month', created_at)
      `,
      [config.start, config.end]
    )
  ]);

  return {
    roleStatusSummary: summaryResult.rows.map((row) => ({
      role: row.role,
      status: row.status,
      total_count: numberValue(row.total_count)
    })),
    accountCreationTrend: trendResult.rows.map((row) => ({
      account_creation_month: row.account_creation_month,
      new_account_count: numberValue(row.new_account_count)
    }))
  };
}

